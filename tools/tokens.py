#!/usr/bin/env python3
"""Writes public/_site/tokens.css from the app's colour palette at a release tag.

The palette is two positional QColor lists in src/ui/Theme.cpp, in the field order of
struct Palette in src/ui/Theme.h. Both files are read from the tag with `git show`, so
the page's colours match the build the screenshots come from. Translucent colours are
composited on bg, the same way the app's tokens() does. Only names and values are
copied; comments in the sources are not.

    python3 tools/tokens.py --tag v26.1029.2229-nightly
"""
import argparse
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_REPO = os.environ.get("PUTGD_REPO", "/home/patrick/work/put.gd")
COLOR = re.compile(r'QColor\(\s*(?:"(#[0-9A-Fa-f]{6})"|(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+))\s*\)')


def fields(header: str) -> list[str]:
    body = re.search(r"struct Palette\s*\{(.*?)\};", header, re.S)
    if not body:
        raise ValueError("struct Palette not found")
    names = []
    for line in re.sub(r"//[^\n]*", "", body.group(1)).split(";"):
        line = line.strip()
        if line.startswith("QColor "):
            names += [n.strip() for n in line[len("QColor "):].split(",")]
    return names


def palette(source: str, name: str) -> list[tuple[int, int, int, int]]:
    block = re.search(r"const Palette " + name + r"\{(.*?)\};", source, re.S)
    if not block:
        raise ValueError(f"palette {name} not found")
    out = []
    for hexa, r, g, b, a in COLOR.findall(block.group(1)):
        if hexa:
            out.append((int(hexa[1:3], 16), int(hexa[3:5], 16), int(hexa[5:7], 16), 255))
        else:
            out.append((int(r), int(g), int(b), int(a)))
    return out


def hexcolor(c, bg) -> str:
    a = c[3] / 255
    return "#" + "".join(f"{round(c[i] * a + bg[i] * (1 - a)):02x}" for i in range(3))


def tokens(header: str, source: str) -> dict[str, dict[str, str]]:
    names = fields(header)
    result = {}
    for scheme in ("dark", "light"):
        values = palette(source, scheme)
        if len(values) != len(names):
            raise ValueError(f"{scheme}: {len(values)} colours for {len(names)} Palette fields")
        bg = values[names.index("bg")]
        result[scheme] = {n: hexcolor(v, bg) for n, v in zip(names, values)}
    return result


def kebab(name: str) -> str:
    return re.sub(r"([A-Z])", r"-\1", name).lower()


def css(values: dict[str, dict[str, str]], tag: str) -> str:
    def block(scheme):
        return "\n".join(f"  --{kebab(n)}: {v};" for n, v in values[scheme].items())
    return (f"/* Generated by tools/tokens.py from Theme.cpp@{tag}. Do not edit. */\n"
            f":root {{\n  color-scheme: dark light;\n{block('dark')}\n}}\n"
            f"@media (prefers-color-scheme: light) {{\n:root {{\n{block('light')}\n}}\n}}\n")


def git_show(repo: str, tag: str, path: str) -> str:
    return subprocess.run(["git", "-C", repo, "show", f"{tag}:{path}"],
                          check=True, capture_output=True, text=True).stdout


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--tag", required=True, help="app release tag, e.g. v26.1029.2229-nightly")
    ap.add_argument("--repo", default=DEFAULT_REPO, help="put.gd-desktop checkout (default $PUTGD_REPO)")
    ap.add_argument("--out", default=str(ROOT / "public/_site/tokens.css"))
    args = ap.parse_args()
    values = tokens(git_show(args.repo, args.tag, "src/ui/Theme.h"),
                    git_show(args.repo, args.tag, "src/ui/Theme.cpp"))
    pathlib.Path(args.out).write_text(css(values, args.tag))
    print(f"wrote {args.out}: {len(values['dark'])} tokens per scheme")
    return 0


if __name__ == "__main__":
    sys.exit(main())
